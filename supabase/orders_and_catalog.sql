-- --- Datos del negocio (fila única) ----------------------------------------
create table if not exists public.business_info (
  id int primary key default 1,
  name text not null,
  tagline text not null,
  address text not null,
  city text not null,
  phone text not null,
  whatsapp text not null,
  instagram text,
  lat double precision not null,
  lng double precision not null,
  google_maps_url text not null,
  rating numeric not null default 0,
  rating_count int not null default 0,
  constraint business_info_singleton check (id = 1)
);

alter table public.business_info enable row level security;

drop policy if exists "business_info_select_public" on public.business_info;
create policy "business_info_select_public" on public.business_info
  for select to anon, authenticated using (true);

drop policy if exists "business_info_update_gerente" on public.business_info;
create policy "business_info_update_gerente" on public.business_info
  for update to authenticated
  using (exists (select 1 from public.profiles where id = auth.uid() and role = 'gerente'))
  with check (exists (select 1 from public.profiles where id = auth.uid() and role = 'gerente'));

